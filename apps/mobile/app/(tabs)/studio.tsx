import * as Haptics from 'expo-haptics';
import { useState } from 'react';
import { KeyboardAvoidingView, Platform, ScrollView, View } from 'react-native';
import { useLocalSearchParams, useRouter } from 'expo-router';
import { Sparkles, Coins, Plug, Wand2 } from 'lucide-react-native';
import { api, newKey, ApiError } from '../../lib/api';
import { useAuth } from '../../lib/auth';
import { useColors } from '../../lib/theme';
import type { Project } from '../../lib/types';
import { Button, Card, Chip, ErrorBox, Field, Label, Row, T } from '../../components/ui';
import { Appear, Swap } from '../../components/motion';

/**
 * One box, one button. Everything else is automatic on the server: one screen vs a full app,
 * number of screens, device, theme & style, Stitch model, and a hidden prompt enhancement
 * (Gemini with the user's own key, else the built-in planner) that is sent only to Stitch.
 */
const IDEAS = [
  'Create a fitness app',
  'Food delivery app for a cloud kitchen in Delhi',
  'Website for my bakery in Gurugram',
  'Fintech home screen with balance card and recent transactions',
  'Landing page for a B2B invoicing SaaS',
  'Habit tracker onboarding screen',
];
const isWebsite = (p: string) => /\b(website|web ?site|landing ?page|web ?page|homepage|portfolio site|blog site)\b/i.test(p);

export default function Studio() {
  const params = useLocalSearchParams<{ kind?: string; prompt?: string }>();
  const { me, refresh } = useAuth();
  const c = useColors();
  const router = useRouter();
  const [prompt, setPrompt] = useState(typeof params.prompt === 'string' ? params.prompt : '');
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<ApiError | null>(null);
  const stitchOn = !!me?.connections.find((x) => x.provider === 'stitch')?.connected;
  const per = 2; // server CREDIT_COSTS.generate_flash (per screen)

  const go = async () => {
    setBusy(true); setErr(null);
    let created: Project | null = null;
    try {
      const web = (isWebsite(prompt) || params.kind === 'website') && !!me?.plan.features.includes('website_studio');
      // "Untitled" is renamed by the server to the planned app name.
      const { project } = await api.post<{ project: Project }>('/projects', { name: 'Untitled', kind: web ? 'website' : 'ui', deviceType: web ? 'DESKTOP' : 'MOBILE' });
      created = project;
      const { job } = await api.post<{ job: { id: string } }>(`/projects/${project.id}/generate`, { prompt: prompt.trim(), pageId: project.pages[0].id, idempotencyKey: newKey(), auto: true });
      refresh(); setPrompt('');
      Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success).catch(() => undefined);
      router.push(`/project/${project.id}?job=${job.id}`);
    } catch (e) {
      // Generation never started: remove the empty project so it doesn't clutter the list or count toward limits.
      if (created) api.del(`/projects/${created.id}`).catch(() => undefined);
      setErr(e as ApiError);
    } finally { setBusy(false); }
  };

  return (
    <KeyboardAvoidingView style={{ flex: 1 }} behavior={Platform.OS === 'ios' ? 'padding' : undefined}>
      <ScrollView contentContainerStyle={{ padding: 16, gap: 16 }} keyboardShouldPersistTaps="handled">
        {me && !stitchOn && (
          <Card index={0} style={{ gap: 8, borderColor: c.amber + '88' }}>
            <Row><Plug size={18} color={c.amber} /><T weight="700" style={{ flex: 1 }}>Connect Google Stitch first</T></Row>
            <T muted size={12}>Designs are generated by Google Stitch in your own Google account. It takes a minute to connect.</T>
            <Button small title="Connect Stitch" onPress={() => router.push('/integrations')} />
          </Card>
        )}
        <Card index={1} style={{ gap: 12 }}>
          <Row><Wand2 size={18} color={c.primary} /><T weight="700" size={16} style={{ flex: 1 }}>What do you want to build?</T></Row>
          <Field multiline value={prompt} onChangeText={setPrompt} maxLength={4000} style={{ minHeight: 150 }} placeholder={'e.g. Create a fitness app\n\nA short idea becomes a complete multi-screen app. Describe one screen and you get exactly that screen.'} />
          <T muted size={12}>We pick the best layout, colours, fonts, device and number of screens for you automatically.</T>
          <Label>Try an idea</Label>
          <Swap id="ideas" style={{ gap: 6 }}>{IDEAS.map((i) => <Chip key={i} label={i} onPress={() => setPrompt(i)} />)}</Swap>
        </Card>
        <ErrorBox error={err} />
        <Appear index={3}><Button title="Generate design" icon={<Sparkles color="#fff" size={18} />} loading={busy} disabled={prompt.trim().length < 5 || (!!me && !stitchOn)} onPress={go} /></Appear>
        <View style={{ alignItems: 'center', gap: 2 }}>
          <Row style={{ justifyContent: 'center' }}><Coins size={14} color={c.amber} /><T muted size={12}>{per} credits per screen · a full app is 3–5 screens</T></Row>
          <T muted size={11}>Refunded automatically if anything fails.</T>
        </View>
      </ScrollView>
    </KeyboardAvoidingView>
  );
}
